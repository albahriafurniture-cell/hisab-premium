/// Helper function to translate string keys based on HiveService settings.
/// Can be called as tr('key') or tr('key', context).
String tr(String key, [BuildContext? context]) {
  final locale = HiveService.instance.getSettings().locale;
  final map = locale == 'ur' ? ur : en;
  return map[key] ?? en[key] ?? key;
}

/// Direct translation helper without BuildContext (useful in controllers/models/dialogs).
String trDirect(String key, {String? locale}) {
  final loc = locale ?? HiveService.instance.getSettings().locale;
  final map = loc == 'ur' ? ur : en;
  return map[key] ?? en[key] ?? key;
}

